interface RecipeSeed {
  id: string
  name: string
  emoji: string
  category: string
  calories: number
  time: number
  ingredients: Array<[string, string]>
  steps: string[]
  nutrition: {
    protein: number
    carbs: number
    fat: number
  }
}

function buildRecipe(seed: RecipeSeed) {
  return {
    id: seed.id,
    name: seed.name,
    emoji: seed.emoji,
    category: seed.category,
    calories: seed.calories,
    time: seed.time,
    ingredients: seed.ingredients.map(([name, amount]) => ({ name, amount })),
    steps: [...seed.steps],
    nutrition: { ...seed.nutrition },
  }
}

